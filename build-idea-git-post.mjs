/**
 * Post-pass for the idea-git build (see build-idea-git.mjs for the pipeline).
 *
 * Reads the esbuild CLI outputs from .tmp-idea-git/ and writes the final
 * artifacts at the plugin root:
 *   - idea-git.client.js — CJS body; the bundled `require("react/jsx-runtime")`
 *     external is replaced with an inlined shim over the host-provided `react`
 *     (the DSH module table may not expose `react/jsx-runtime`).
 *   - idea-git.host.js — ESM host half, passed through unchanged (guarding
 *     that no dynamic relative import survived bundling).
 */

import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const TMP = path.join(HERE, '.tmp-idea-git')

const clientBundle = readFileSync(path.join(TMP, 'client.bundle.js'), 'utf8')
const hostBundle = readFileSync(path.join(TMP, 'host.bundle.js'), 'utf8')

/* Inlined .vendor/zhuweiyou-dsh-idea-git-946e7ad/src/client/jsx-runtime.ts */
const shim = `(function(){ /* jsx-runtime shim (see build-idea-git-post.mjs) */
var React = require("react");
function normalize(type, props, key) {
  if (key === undefined || key === null) return props == null ? {} : props;
  return Object.assign({}, props, { key: key });
}
function jsx(type, props, key) {
  return React.createElement(type, normalize(type, props, key));
}
return { Fragment: React.Fragment, jsx: jsx, jsxs: jsx, jsxDEV: jsx };
})()`

let client = clientBundle.replace(/require\("react\/jsx-(dev-)?runtime"\)/g, '(__dig_jsx_runtime)')
const usesRuntime = client !== clientBundle
if (!usesRuntime) throw new Error('the client bundle never required the jsx runtime — check the jsx transform')
client = `var __dig_jsx_runtime = ${shim};\n` + client

const clientOut = `// Generated by build-idea-git.mjs + build-idea-git-post.mjs (esbuild CLI) — edit .vendor/zhuweiyou-dsh-idea-git-946e7ad/src/client instead.\n${client}`
writeFileSync(path.join(HERE, 'idea-git.client.js'), clientOut)
console.log(`idea-git.client.js written (${clientOut.length} bytes)`)

if (/import\s*\(\s*["']\.\/(rpc|git\/|settings)/.test(hostBundle)) {
  throw new Error('the host bundle still contains a dynamic relative import — it was not bundled')
}
const hostOut = `// Generated by build-idea-git.mjs + build-idea-git-post.mjs (esbuild CLI) — edit .vendor/zhuweiyou-dsh-idea-git-946e7ad/src/host instead.\n${hostBundle}`
writeFileSync(path.join(HERE, 'idea-git.host.js'), hostOut)
console.log(`idea-git.host.js written (${hostOut.length} bytes)`)

if (!existsSync(path.join(HERE, '.tmp-idea-git', 'src', 'index.tsx'))) {
  throw new Error('prep output missing — run node build-idea-git.mjs first')
}
